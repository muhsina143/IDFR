        foreach ($fieldsDefinitions as $key => $def) {
            $createdFields[$key] = ProfessionalFormField::updateOrCreate(
                ['field_key' => $key],
                [
                    'label' => $def['label'],
                    'field_type' => $def['field_type'],
                    'placeholder' => $def['placeholder'] ?? null,
                    'help_text' => $def['help_text'] ?? null,
                    'default_value' => $def['default_value'] ?? null,
                    'options' => $def['options'] ?? null,
                    'validation_rules' => $def['validation_rules'] ?? null,
                    'is_required' => $def['is_required'] ?? false,
                    'is_common' => $def['is_common'] ?? false,
                    'width' => $def['width'] ?? 'half',
                    'display_order' => $def['display_order'] ?? 50,
                    'is_active' => true,
                ]
            );
        }

        // 3. Create Categories and Attach Pivot Fields
        foreach ($categoriesData as $cData) {
            $cat = ProfessionalCategory::updateOrCreate(
                ['slug' => $cData['slug']],
                [
                    'name' => $cData['name'],
                    'hero_title' => $cData['hero_title'],
                    'description' => $cData['description'],
                    'form_title' => $cData['form_title'],
                    'form_lead' => $cData['form_lead'],
                    'default_photo' => $cData['default_photo'],
                    'display_order' => $cData['display_order'],
                    'is_active' => true,
                ]
            );

            // Build ordered field list for this category
            $dedicatedServiceKey = 'service_'.str_replace('-', '_', $cData['slug']);
            $serviceKeyToAttach = isset($createdFields[$dedicatedServiceKey]) ? $dedicatedServiceKey : 'service';

            $orderedKeys = [
                'name' => 10,
                'profession' => 20,
                'place' => 30,
                'experience' => 40,
                'phone' => 45,
                'email' => 50,
                'about' => 60,
                $cData['specific_field'] => 70,
                $serviceKeyToAttach => 80,
                'outstation' => 90,
            ];

            foreach ($orderedKeys as $fieldKey => $order) {
                if (! isset($createdFields[$fieldKey])) {
                    continue;
                }
                $fieldModel = $createdFields[$fieldKey];

                $pivotData = [
                    'display_order' => $order,
                    'is_active' => true,
                ];

                // Category-specific overrides
                if ($fieldKey === $cData['specific_field']) {
                    $pivotData['label_override'] = $cData['specific_label'];
                    $pivotData['placeholder_override'] = $cData['specific_placeholder'];
                }

                if ($fieldKey === 'service') {
                    $pivotData['label_override'] = $cData['services_legend'];
                    $pivotData['options_override'] = $cData['services'];
                }

                if ($fieldKey === 'profession') {
                    $pivotData['placeholder_override'] = $cData['name'];
                }

                CategoryFormField::updateOrCreate(
                    [
                        'category_id' => $cat->id,
                        'field_id' => $fieldModel->id,
                    ],
                    $pivotData
                );
            }
        }
    }
